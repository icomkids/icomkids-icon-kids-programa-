-- Maré Particular: isolated schema, accessed only by the server-side service role.
-- Apply after inspecting the existing project. Never expose the private key to a browser.
begin;
create schema if not exists mare_particular;
revoke all on schema mare_particular from public, anon, authenticated;
grant usage on schema mare_particular to service_role;

create table if not exists mare_particular.settings (
  id integer primary key check(id=1), value jsonb not null
);
create table if not exists mare_particular.reservations (
  id uuid primary key, code text unique not null, name text not null, email text not null,
  phone text not null, note text not null default '', checkin date not null, checkout date not null,
  guests integer not null check(guests>0), nights integer not null check(nights>0),
  subtotal bigint not null check(subtotal>=0), cleaning bigint not null check(cleaning>=0),
  total bigint not null check(total=subtotal+cleaning),
  status text not null check(status in ('pending','confirmed','cancelled','expired')),
  created_at timestamptz not null default now(), expires_at timestamptz,
  snapshot jsonb not null, request_key text unique not null,
  check(checkout>checkin and nights=checkout-checkin)
);
create table if not exists mare_particular.blocks (
  id uuid primary key, start date not null, "end" date not null, reason text not null,
  check("end">start)
);
create table if not exists mare_particular.occupancy (
  day date primary key, reservation_id uuid references mare_particular.reservations(id),
  block_id uuid references mare_particular.blocks(id),
  check((reservation_id is null)<>(block_id is null))
);
create index if not exists mp_occupancy_reservation_idx on mare_particular.occupancy(reservation_id);
create index if not exists mp_occupancy_block_idx on mare_particular.occupancy(block_id);
create index if not exists mp_reservation_expiry_idx on mare_particular.reservations(expires_at) where status='pending';
create table if not exists mare_particular.audit (
  id bigint generated by default as identity primary key, action text not null,
  record_id text, created_at timestamptz not null default now()
);
create table if not exists mare_particular.imports (
  source text primary key, imported_at timestamptz not null default now()
);
alter table mare_particular.settings enable row level security;
alter table mare_particular.reservations enable row level security;
alter table mare_particular.blocks enable row level security;
alter table mare_particular.occupancy enable row level security;
alter table mare_particular.audit enable row level security;
alter table mare_particular.imports enable row level security;
revoke all on all tables in schema mare_particular from public, anon, authenticated;
revoke all on all sequences in schema mare_particular from public, anon, authenticated;
grant select,insert,update,delete on all tables in schema mare_particular to service_role;
grant usage,select on all sequences in schema mare_particular to service_role;

create or replace function public.mp_dispatch(p_operation text,p_data jsonb default '{}'::jsonb)
returns jsonb language plpgsql security invoker set search_path='' as $$
declare
  cfg jsonb; imported jsonb; item jsonb; answer jsonb; r mare_particular.reservations%rowtype;
  start_day date; end_day date; n integer; people integer; subtotal_value bigint;
  cleaning_value bigint; total_value bigint; identifier uuid; request_id text;
  action_status text; current_stamp timestamptz:=now();
begin
  if current_user not in ('service_role','postgres') then
    raise insufficient_privilege using message='Acesso restrito ao servidor.';
  end if;
  -- Every mutation uses one apartment lock and one database transaction.
  perform pg_catalog.pg_advisory_xact_lock(713904261);
  if p_operation='health' then return jsonb_build_object('ok',true); end if;
  if p_operation='bootstrap' then
    imported:=p_data->'snapshot';
    if imported is not null and imported<>'null'::jsonb and not exists(select 1 from mare_particular.imports where source='sqlite-v1') then
      if exists(select 1 from mare_particular.reservations) or exists(select 1 from mare_particular.blocks) then
        raise exception 'A importação precisa ser revisada: já existem dados no destino.';
      end if;
      insert into mare_particular.settings(id,value) values(1,coalesce(imported->'config',p_data->'config')) on conflict(id) do nothing;
      for item in select value from jsonb_array_elements(coalesce(imported->'reservations','[]'::jsonb)) loop
        insert into mare_particular.reservations(id,code,name,email,phone,note,checkin,checkout,guests,nights,subtotal,cleaning,total,status,created_at,expires_at,snapshot,request_key)
        values((item->>'id')::uuid,item->>'code',item->>'name',item->>'email',item->>'phone',item->>'note',
          (item->>'checkin')::date,(item->>'checkout')::date,(item->>'guests')::integer,(item->>'nights')::integer,
          (item->>'subtotal')::bigint,(item->>'cleaning')::bigint,(item->>'total')::bigint,item->>'status',
          (item->>'created_at')::timestamptz,(item->>'expires_at')::timestamptz,(item->>'snapshot')::jsonb,item->>'request_key');
      end loop;
      for item in select value from jsonb_array_elements(coalesce(imported->'blocks','[]'::jsonb)) loop
        insert into mare_particular.blocks values((item->>'id')::uuid,(item->>'start')::date,(item->>'end')::date,item->>'reason');
      end loop;
      for item in select value from jsonb_array_elements(coalesce(imported->'occupancy','[]'::jsonb)) loop
        insert into mare_particular.occupancy values((item->>'day')::date,(item->>'reservation_id')::uuid,(item->>'block_id')::uuid);
      end loop;
      for item in select value from jsonb_array_elements(coalesce(imported->'audit','[]'::jsonb)) loop
        insert into mare_particular.audit(action,record_id,created_at) values(item->>'action',item->>'record_id',(item->>'created_at')::timestamptz);
      end loop;
      insert into mare_particular.imports(source) values('sqlite-v1');
      insert into mare_particular.audit(action) values('storage.imported');
    end if;
    insert into mare_particular.settings values(1,p_data->'config') on conflict(id) do nothing;
    return jsonb_build_object('ok',true);
  end if;
  select value into strict cfg from mare_particular.settings where id=1;
  for identifier in select id from mare_particular.reservations where status='pending' and expires_at<current_stamp loop
    delete from mare_particular.occupancy where reservation_id=identifier;
    update mare_particular.reservations set status='expired' where id=identifier;
    insert into mare_particular.audit(action,record_id) values('reservation.expired',identifier::text);
  end loop;
  if p_operation in ('public','owner') then
    answer:=jsonb_build_object('config',cfg,'busy',(select coalesce(jsonb_agg(day order by day),'[]'::jsonb) from mare_particular.occupancy));
    if p_operation='owner' then
      answer:=answer||jsonb_build_object(
        'reservations',(select coalesce(jsonb_agg(to_jsonb(x)-'snapshot'-'request_key' order by x.created_at desc),'[]'::jsonb) from mare_particular.reservations x),
        'blocks',(select coalesce(jsonb_agg(to_jsonb(x) order by x.start),'[]'::jsonb) from mare_particular.blocks x),
        'audit',(select coalesce(jsonb_agg(to_jsonb(x) order by x.id desc),'[]'::jsonb) from (select * from mare_particular.audit order by id desc limit 30) x));
    end if;
    return answer;
  elsif p_operation='create' then
    start_day:=(p_data->>'checkin')::date;end_day:=(p_data->>'checkout')::date;
    n:=end_day-start_day;people:=(p_data->>'guests')::integer;request_id:=p_data->>'requestKey';
    if request_id is null or request_id!~'^[a-zA-Z0-9-]{16,100}$' then raise exception 'Atualize a página e tente novamente.'; end if;
    select * into r from mare_particular.reservations where request_key=request_id;
    if found then
      if r.email<>p_data->>'email' or r.checkin<>start_day or r.checkout<>end_day or r.guests<>people then raise exception 'Solicitação já utilizada.';end if;
      return to_jsonb(r)-'snapshot'-'request_key';
    end if;
    if start_day is null or end_day is null or start_day<(current_stamp at time zone 'America/Sao_Paulo')::date
      or n<(cfg->>'minNights')::integer or n>(cfg->>'maxNights')::integer or n>365
      or people is null or people<1 or people>(cfg->>'guests')::integer then raise exception 'Datas ou quantidade de hóspedes inválidas.';end if;
    if coalesce((p_data->>'accepted')::boolean,false) is not true then raise exception 'Aceite as regras para continuar.';end if;
    if length(coalesce(p_data->>'name','')) not between 3 and 120
      or length(coalesce(p_data->>'email','')) not between 3 and 200
      or length(coalesce(p_data->>'phone','')) not between 10 and 30
      or length(coalesce(p_data->>'note',''))>1000 then raise exception 'Dados do hóspede inválidos.';end if;
    if exists(select 1 from mare_particular.occupancy where day>=start_day and day<end_day) then raise exception 'Essas datas já estão ocupadas. Escolha outro período.';end if;
    select sum(case when extract(isodow from start_day+i) in (5,6) then (cfg->>'weekend')::bigint else (cfg->>'weekday')::bigint end)
      into subtotal_value from generate_series(0,n-1) as t(i);
    cleaning_value:=(cfg->>'cleaning')::bigint;total_value:=subtotal_value+cleaning_value;identifier:=gen_random_uuid();
    insert into mare_particular.reservations(id,code,name,email,phone,note,checkin,checkout,guests,nights,subtotal,cleaning,total,status,created_at,expires_at,snapshot,request_key)
      values(identifier,'MP-'||upper(substr(replace(identifier::text,'-',''),1,8)),p_data->>'name',p_data->>'email',p_data->>'phone',coalesce(p_data->>'note',''),
        start_day,end_day,people,n,subtotal_value,cleaning_value,total_value,'pending',current_stamp,current_stamp+interval '24 hours',
        jsonb_build_object('config',cfg,'acceptedAt',current_stamp,'demo',p_data->'demo','subtotal',subtotal_value,'cleaning',cleaning_value,'total',total_value),request_id)
      returning * into r;
    insert into mare_particular.occupancy(day,reservation_id) select start_day+i,identifier from generate_series(0,n-1) as t(i);
    insert into mare_particular.audit(action,record_id) values('reservation.requested',identifier::text);
    return to_jsonb(r)-'snapshot'-'request_key';
  elsif p_operation='settings' then
    if jsonb_typeof(p_data->'config')<>'object' then raise exception 'Configuração inválida.';end if;
    update mare_particular.settings set value=p_data->'config' where id=1;
    insert into mare_particular.audit(action) values('settings.updated');return jsonb_build_object('ok',true);
  elsif p_operation='transition' then
    identifier:=(p_data->>'id')::uuid;action_status:=p_data->>'status';
    if action_status not in ('confirmed','cancelled') or action_status is null then raise exception 'Situação inválida.';end if;
    select * into r from mare_particular.reservations where id=identifier;
    if not found then raise exception 'Reserva não encontrada.';end if;
    if r.status not in ('pending','confirmed') then raise exception 'Esta reserva já foi encerrada.';end if;
    if action_status='cancelled' then delete from mare_particular.occupancy where reservation_id=identifier;end if;
    update mare_particular.reservations set status=action_status,expires_at=null where id=identifier;
    insert into mare_particular.audit(action,record_id) values('reservation.'||action_status,identifier::text);return jsonb_build_object('ok',true);
  elsif p_operation='block' then
    start_day:=(p_data->>'start')::date;end_day:=(p_data->>'end')::date;n:=end_day-start_day;
    if start_day is null or end_day is null or n not between 1 and 365 or length(coalesce(p_data->>'reason',''))>200 then raise exception 'Período inválido.';end if;
    if exists(select 1 from mare_particular.occupancy where day>=start_day and day<end_day) then raise exception 'Há uma reserva ou bloqueio nesse período.';end if;
    identifier:=gen_random_uuid();insert into mare_particular.blocks values(identifier,start_day,end_day,coalesce(p_data->>'reason','Uso da proprietária'));
    insert into mare_particular.occupancy(day,block_id) select start_day+i,identifier from generate_series(0,n-1) as t(i);
    insert into mare_particular.audit(action,record_id) values('block.created',identifier::text);return jsonb_build_object('ok',true);
  elsif p_operation='unblock' then
    identifier:=(p_data->>'id')::uuid;
    if not exists(select 1 from mare_particular.blocks where id=identifier) then raise exception 'Bloqueio não encontrado.';end if;
    delete from mare_particular.occupancy where block_id=identifier;delete from mare_particular.blocks where id=identifier;
    insert into mare_particular.audit(action,record_id) values('block.removed',identifier::text);return jsonb_build_object('ok',true);
  end if;
  raise exception 'Operação não reconhecida.';
end;
$$;
revoke all on function public.mp_dispatch(text,jsonb) from public,anon,authenticated;
grant execute on function public.mp_dispatch(text,jsonb) to service_role;
notify pgrst,'reload schema';
commit;
